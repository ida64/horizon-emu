/// Optional commands, answered with [`UNKNOWN_COMMAND`]:
/// - 0xfc16 (parameter 0xffc0), sent once right after the patch launch with
///   no completion callback (text 0xad0f8): only the command credit is used.
/// - 0xfce9, Broadcom's LE resolving-list offload (sub-op 4 = clear, answer
///   = free entries; the same layout as Android's later 0xfd55): text
///   0x9e3b0 zeroes the host's offload state first and the completion
///   0x9d030 stores the size only on success, so the host keeps resolving
///   private addresses itself.
/// - 0xfd53, Android-style LE Get Vendor Capabilities, whose completion is a
///   no-op (`nullsub_19`, text 0x9e3b0).
/// - 0xfc1d, Read SCO PCM Int Params (public btbcm): completion 0x9f150
///   stores the parameters only on success.
/// - 0xfcc3, completion 0x9f0b0 stores a capability byte, zero on failure,
///   which 0x9ee60 reads as "feature 0xfcfa absent" (returns 0xa).
/// - 0x0c58 Read Inquiry Response TX Power Level, an RF calibration value:
///   completion 0xb2430 reports failure to 0x4e5b0, which then leaves the
///   TX power out (null pointer) instead of storing it.
const OPTIONAL: &[u16] = &[0xfc16, 0xfce9, 0xfd53, 0xfc1d, 0xfcc3, 0x0c58];
/// Controller features from Read Controller Features: 0x0f, as public
/// btbcm's log of the same BCM4356A3 silicon prints ("BCM: features 0x0f",
/// Linux patch "btbcm: Add entry for BCM4356A3 UART bluetooth"); the other
/// seven bytes are not public and assumed zero. `bluetooth` text 0x9f1e0
/// only stores them.
const CONTROLLER_FEATURES: [u8; 8] = [0x0f, 0, 0, 0, 0, 0, 0, 0];
/// Chip id 122 from Read Verbose Config Version Info, as the same Linux log
/// prints ("BCM: chip id 122"); target id and build numbers are not public
/// and assumed zero. `bluetooth` text 0x9f100 only tests the chip id
/// against 45, which this chip is not.
const VERBOSE_CONFIG: [u8; 6] = [122, 0, 0, 0, 0, 0];
const UNKNOWN_COMMAND: u8 = 0x01;

/// The supported-commands mask: exactly the standard commands above.
fn supported_commands() -> [u8; 64] {
    let mut mask = [0; 64];
    for &(_, _, bit) in COMMANDS {
        if let Some((octet, bit)) = bit {
            mask[octet] |= 1 << bit;
        }
    }
    mask
}

/// Link keys the controller is taken to have room for: the console pairs
/// at most eight controllers.
const MAX_LINK_KEYS: usize = 8;

/// Controller state the host can set and read back.
#[derive(Default)]
pub(super) struct Controller {
    /// Between Download Minidriver and Launch RAM.
    download: bool,
    /// Public address set by Broadcom Write BD_ADDR. It survives HCI Reset,
    /// which public Linux relies on (`hci_dev_open_sync` writes it through
    /// btbcm before the init sequence's reset).
    address: [u8; 6],
    /// LMP features page 1 (host supported): bit 0 SSP, bit 1 LE, bit 2
    /// simultaneous LE and BR/EDR, bit 3 Secure Connections (Vol 2 Part C
    /// §3.3).
    host_features: u8,
    /// LE white list entries (address type, address), at most
    /// [`LE_WHITE_LIST_SIZE`].
    white_list: Vec<[u8; 7]>,
    /// The controller's random number generator (LE Rand): SplitMix64 from
    /// a fixed seed, so that runs are reproducible, as the secure monitor's
    /// generator is.
    random: u64,
    /// LE advertising packet content filter entries: (sub-op = filter
    /// type, filter index).
    filters: Vec<(u8, u8)>,
    /// Link keys the host stored, by address. They outlast HCI Reset, as
    /// the controller's own storage does (Core spec vol 4 part E 7.3.9).
    link_keys: Vec<([u8; 6], [u8; 16])>,
}

impl Controller {
    /// Executes one complete command and writes its Command Complete
    /// return parameters (status first) into `reply`, returning their
    /// length; `None` for commands not modeled.
    pub(super) fn execute(&mut self, op: u16, p: &[u8], reply: &mut [u8; 252]) -> Option<usize> {
        if OPTIONAL.contains(&op) {
            reply[0] = UNKNOWN_COMMAND;
            return Some(1);
        }
        let &(_, len, _) = COMMANDS.iter().find(|c| c.0 == op)?;
        if len != usize::MAX && p.len() != len {
            return None;
        }
        let (status, r) = reply.split_first_mut()?;
        *status = SUCCESS;
        let n = match op {
            0x0c03 => {
                // Reset returns the host-set state to its defaults; the
                // vendor-written address persists (see `address`).
                self.download = false;
                self.host_features = 0;
                self.white_list.clear();
                self.filters.clear();
                0
            }
            // Write Stored Link Key (Core spec vol 4 part E 7.3.9): a
            // count, then an address and a key for each; returns how many
            // were written. Before the console sleeps `bluetooth` deletes
            // all and stores the keys of the paired controllers, so that
            // the controller can answer one of them by itself. The room a
            // real controller has for keys is not known; more than
            // [`MAX_LINK_KEYS`] stops the machine rather than guess what
            // is reported then.
            0x0c11 => {
                let (&count, keys) = p.split_first()?;
                let (keys, []) = keys.as_chunks::<22>() else {
                    return None;
                };
                if keys.len() != usize::from(count) {
                    return None;
                }
                for entry in keys {
                    let (address, key) = entry.split_first_chunk::<6>()?;
                    let key: [u8; 16] = key.try_into().ok()?;
                    self.link_keys.retain(|(stored, _)| stored != address);
                    self.link_keys.push((*address, key));
                }
                if self.link_keys.len() > MAX_LINK_KEYS {
                    return None;
                }
                r[0] = count;
                1
            }
            // Delete Stored Link Key (7.3.10): address, then whether all
            // are meant; returns how many were deleted.
            0x0c12 => match p[6] {
                0 | 1 => {
                    let before = self.link_keys.len();
                    self.link_keys
                        .retain(|(address, _)| p[6] == 0 && address[..] != p[..6]);
                    let deleted = (before - self.link_keys.len()) as u16;
                    r[..2].copy_from_slice(&deleted.to_le_bytes());
                    2
                }
                _ => {
                    *status = INVALID_PARAMETERS;
                    0
                }
            },
            0x0c56 => match p[0] {
                0 | 1 => {
                    self.host_features = self.host_features & !1 | p[0];
                    0
                }
                _ => {
                    *status = INVALID_PARAMETERS;
                    0
                }
            },
            0x0c7a => match p[0] {
                0 | 1 => {
                    self.host_features = self.host_features & !8 | p[0] << 3;
                    0
                }
                _ => {
                    *status = INVALID_PARAMETERS;
                    0
                }
            },
            0x0c6d => match (p[0], p[1]) {
                (0..=1, 0..=1) => {
                    self.host_features = self.host_features & !6 | p[0] << 1 | p[1] << 2;
                    0
                }
                _ => {
                    *status = INVALID_PARAMETERS;
                    0
                }
            },
            // Writes of settings this model keeps no further use for: the
            // controller accepts them and, with no radio traffic modeled,
            // nothing they configure becomes observable.
            0x080f | 0x0c01 | 0x0c0a | 0x0c13 | 0x0c16 | 0x0c18 | 0x0c1a | 0x0c1c | 0x0c1e
            | 0x0c24 | 0x0c26 | 0x0c33 | 0x0c3f | 0x0c43 | 0x0c45 | 0x0c47 | 0x0c52 | 0x0c63
            | 0x0c6e | 0x1804 | 0x2001 | 0x2005 | 0x2006 | 0x2008 | 0x2009 | 0x200a | 0x200b
            | 0x200c => 0,
            0x2010 => {
                self.white_list.clear();
                0
            }
            0x2011 => {
                let entry: [u8; 7] = p.try_into().ok()?;
                if !self.white_list.contains(&entry) {
                    if self.white_list.len() == usize::from(LE_WHITE_LIST_SIZE) {
                        *status = MEMORY_CAPACITY_EXCEEDED;
                    } else {
                        self.white_list.push(entry);
                    }
                }
                0
            }
            0x2012 => {
                self.white_list.retain(|e| e[..] != *p);
                0
            }
            0x1001 => {
                r[0] = VERSION;
                r[1..3].copy_from_slice(&HCI_REVISION.to_le_bytes());
                r[3] = VERSION;
                r[4..6].copy_from_slice(&MANUFACTURER.to_le_bytes());
                r[6..8].copy_from_slice(&LMP_SUBVERSION.to_le_bytes());
                8
            }
            0x1002 => {
                r[..64].copy_from_slice(&supported_commands());
                64
            }
            0x1003 => {
                r[..8].copy_from_slice(&FEATURES);
                8
            }
            0x1004 => {
                r[0] = p[0];
                r[1] = MAX_FEATURES_PAGE;
                r[2..10].copy_from_slice(&match p[0] {
                    0 => FEATURES,
                    1 => [self.host_features, 0, 0, 0, 0, 0, 0, 0],
                    2 => FEATURES_PAGE2,
                    _ => {
                        *status = INVALID_PARAMETERS;
                        [0; 8]
                    }
                });
                10
            }
            0x1005 => {
                r[0..2].copy_from_slice(&ACL_LENGTH.to_le_bytes());
                r[2] = SCO_LENGTH;
                r[3..5].copy_from_slice(&ACL_PACKETS.to_le_bytes());
                r[5..7].copy_from_slice(&SCO_PACKETS.to_le_bytes());
                7
            }
            0x1009 => {
                r[..6].copy_from_slice(&self.address);
                6
            }
            0x2002 => {
                r[..3].copy_from_slice(&LE_BUFFERS);
                3
            }
            0x2003 => {
                r[..8].copy_from_slice(&LE_FEATURES);
                8
            }
            0x200f => {
                r[0] = LE_WHITE_LIST_SIZE;
                1
            }
            0x2018 => {
                self.random = self.random.wrapping_add(0x9e37_79b9_7f4a_7c15);
                let mut z = self.random;
                z = (z ^ (z >> 30)).wrapping_mul(0xbf58_476d_1ce4_e5b9);
                z = (z ^ (z >> 27)).wrapping_mul(0x94d0_49bb_1331_11eb);
                r[..8].copy_from_slice(&(z ^ (z >> 31)).to_le_bytes());
                8
            }
            0x201c => {
                r[..8].copy_from_slice(&LE_STATES);
                8
            }
            0xfc01 => {
                self.address.copy_from_slice(p);
                0
            }
            0xfc6e => {
                r[..8].copy_from_slice(&CONTROLLER_FEATURES);
                8
            }
            0xfc79 => {
                r[..6].copy_from_slice(&VERBOSE_CONFIG);
                6
            }
            // Public hci_bcm.c: Update UART Baud Rate, two zero bytes then
            // the rate. The emulated wire has no sampling clock, so the
            // rate cannot corrupt bytes.
            0xfc18 if p[0..2] == [0, 0] => 0,
            // Public btbcm.c: Download Minidriver, Write RAM (32-bit
            // address, data) and Launch RAM (`bluetooth` text 0x9e660,
            // 0x9e920, 0x9eaa0). The patch is acknowledged, not executed:
            // this model is the patched controller.
            0xfc2e => {
                self.download = true;
                0
            }
            0xfc4c if self.download && (5..=255).contains(&p.len()) => 0,
            0xfc4e if self.download => {
                self.download = false;
                0
            }
            // Public hci_bcm.c (`bcm_set_sleep_mode`): Write Sleep Mode,
            // 12 bytes, mode first. `bluetooth` text 0x8a9a0 sends mode 0,
            // no sleep: the controller stays awake and never toggles the
            // host-wake line, which is the idle this model is.
            0xfc27 if p.iter().all(|&b| b == 0) => 0,
            // When the console goes to sleep `bluetooth` sends mode 1,
            // UART sleep, all else zero: no idle thresholds, both wake
            // lines active low (`struct bcm_set_sleep_mode` in public
            // `btbcm.h`). The controller may then sleep while the host
            // holds BT_WAKE released, and wakes the host through
            // HOST_WAKE when it has something for it. With no radio
            // traffic modeled it never has: accepting the mode changes
            // nothing this controller does. Other settings are not
            // modeled.
            0xfc27 if p[0] == 1 && p[1..].iter().all(|&b| b == 0) => 0,
            // Switchbrew (btdrv SetAdapterProperty type 3): BSA message
            // 0x8ce sends 0xfd98 with a "non-zero" flag and a byte-swapped
            // address (text 0x4fc90). Completion 0x51d40 turns any failure
            // into error 2111 for btm, so the patched controller accepts
            // it; nothing an idle controller does reads it back, so it is
            // not kept.
            0xfd98 if p[0] <= 1 => 0,
            // Switchbrew (btdrv EnableRadio): 0xfc34 carries the bool;
            // completion 0x51db0 turns failure into error 2119. With no
            // radio traffic modeled, the switch changes nothing observable.
            0xfc34 if p[0] <= 1 => 0,
            // Two flags from BSA message 0x8ce (text 0x4fc90); completion
            // 0x51bf0 turns failure into error 2120 for btm.
            0xfd8d if p[0] <= 1 && p[1] <= 1 => 0,
            // The last command of `bluetooth`'s sequence for the console
            // going to sleep, always with 1: Write Sleep Mode (UART), the
            // link keys of the paired controllers into the controller's
            // store, then this (text 0x51fe0, 0x525e0). Its completion
            // (0x526f0) reads the status alone and reports failure to btm
            // as error 2118. Public sources do not name it; by its place
            // it arms the controller to wake the host for one of the
            // stored controllers [inference]. With no radio traffic
            // modeled none ever calls, so the patched controller accepting
            // it is all there is to it.
            0xfd90 if p[0] == 1 => 0,
            // LE advertising packet content filter (Android's 0xfd57 layout,
            // public `btm_ble_adv_filter.c`, facts only). Sub-op 0 enables
            // or disables the feature: status, sub-op, action — the 3-byte
            // answer completion 0x9b8a0 accepts. Sub-ops 1 (filter
            // parameters) to 7 (service data) add (0), delete (1) or clear
            // (2) entries of their type for a filter index and answer with
            // the entries still free as a fourth byte. With no advertiser
            // around, filtering never matches anything.
            0xfd57 if p.len() == 2 && p[0] == 0 && p[1] <= 1 => {
                r[0] = 0;
                r[1] = p[1];
                2
            }
            // Sub-op 1 (filter parameters, Android's
            // BTM_BLE_META_PF_FEAT_SEL) with action 2 (clear,
            // BTM_BLE_SCAN_COND_CLEAR) and no filter index: the clearing of
            // every filter's parameters that `BTM_BleAdvFilterParamSetup`
            // sends as sub-op and action alone. Answered like the other
            // sub-ops: status, sub-op, action, entries free. Completion
            // 0x9b8a0 takes three or four return bytes and, for sub-op 1,
            // hands action, status and free count to the waiting caller.
            0xfd57 if p == [1, 2] => {
                self.filters.retain(|e| e.0 != 1);
                r[0] = 1;
                r[1] = 2;
                r[2] = APCF_ENTRIES as u8;
                3
            }
            0xfd57 if p.len() >= 3 && (1..=7).contains(&p[0]) && p[1] <= 2 => {
                let (kind, action, index) = (p[0], p[1], p[2]);
                match action {
                    0 if self.filters.iter().filter(|e| e.0 == kind).count() == APCF_ENTRIES => {
                        *status = MEMORY_CAPACITY_EXCEEDED;
                    }
                    0 => self.filters.push((kind, index)),
                    1 => {
                        if let Some(at) = self.filters.iter().position(|&e| e == (kind, index)) {
                            self.filters.remove(at);
                        }
                    }
                    _ => self.filters.retain(|e| e.0 != kind),
                }
                r[0] = kind;
                r[1] = action;
                r[2] = (APCF_ENTRIES - self.filters.iter().filter(|e| e.0 == kind).count()) as u8;
                3
            }
            // One to 0x40 inquiry access codes (Vol 4 Part E §7.3.45),
            // used only when the controller answers inquiries.
            0x0c3a
                if !p.is_empty()
                    && (1..=0x40).contains(&p[0])
                    && p.len() == 1 + 3 * usize::from(p[0]) =>
            {
                0
            }
            _ => return None,
        };
        Some(n + 1)
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn run(c: &mut Controller, op: u16, p: &[u8]) -> Option<Vec<u8>> {
        let mut reply = [0; 252];
        c.execute(op, p, &mut reply).map(|n| reply[..n].to_vec())
    }

    #[test]
    fn identity_matches_the_consoles_record() {
        let mut c = Controller::default();
        assert_eq!(
            run(&mut c, 0x1001, &[]).unwrap(),
            [0, 8, 0, 0, 8, 15, 0, 0x09, 0x24]
        );
        assert_eq!(
            run(&mut c, 0x1003, &[]).unwrap()[1..],
            [0xbf, 0xfe, 0xcf, 0xfe, 0xdb, 0xff, 0x7b, 0x87]
        );
        assert_eq!(
            run(&mut c, 0x1005, &[]).unwrap(),
            [0, 0xfd, 3, 64, 8, 0, 1, 0]
        );
    }

    #[test]
    fn supported_commands_announce_exactly_the_modeled_standard_set() {
        let mask = run(&mut Controller::default(), 0x1002, &[]).unwrap();
        assert_eq!(mask.len(), 65);
        // Read Local Extended Features, which `bluetooth` text 0xadb10 tests.
        assert_eq!(mask[1 + 14] & 0x40, 0x40);
        // Inquiry (octet 0 bit 0) is not modeled, so not announced.
        assert_eq!(mask[1] & 1, 0);
    }

    #[test]
    fn host_features_follow_host_writes_and_reset() {
        let mut c = Controller::default();
        assert_eq!(run(&mut c, 0x0c56, &[1]).unwrap(), [0]);
        assert_eq!(run(&mut c, 0x0c6d, &[1, 1]).unwrap(), [0]);
        let page1 = run(&mut c, 0x1004, &[1]).unwrap();
        assert_eq!(page1[..4], [0, 1, 2, 7]);
        assert_eq!(run(&mut c, 0x0c56, &[2]).unwrap(), [INVALID_PARAMETERS]);
        assert_eq!(run(&mut c, 0x1004, &[3]).unwrap()[0], INVALID_PARAMETERS);
        run(&mut c, 0x0c03, &[]).unwrap();
        assert_eq!(run(&mut c, 0x1004, &[1]).unwrap()[3], 0);
    }

    #[test]
    fn stored_link_keys_are_counted_replaced_and_outlast_reset() {
        let mut c = Controller::default();
        let entry = |address: u8, key: u8| [[address; 6].as_slice(), &[key; 16]].concat();
        let two = [&[2][..], &entry(1, 0xAA), &entry(2, 0xBB)].concat();
        assert_eq!(run(&mut c, 0x0c11, &two).unwrap(), [0, 2]);
        // The same address again replaces its key.
        let again = [&[1][..], &entry(1, 0xCC)].concat();
        assert_eq!(run(&mut c, 0x0c11, &again).unwrap(), [0, 1]);
        run(&mut c, 0x0c03, &[]).unwrap();
        // One by address, then all that is left.
        assert_eq!(
            run(&mut c, 0x0c12, &[1, 1, 1, 1, 1, 1, 0]).unwrap(),
            [0, 1, 0]
        );
        assert_eq!(run(&mut c, 0x0c12, &[0; 7]).unwrap(), [0, 0, 0]);
        assert_eq!(
            run(&mut c, 0x0c12, &[0, 0, 0, 0, 0, 0, 1]).unwrap(),
            [0, 1, 0]
        );
        // A count that does not match what follows is not a command.
        assert_eq!(run(&mut c, 0x0c11, &two[..23]), None);
    }

    #[test]
    fn written_address_survives_reset() {
        let mut c = Controller::default();
        run(&mut c, 0xfc01, &[1, 2, 3, 4, 5, 6]).unwrap();
        run(&mut c, 0x0c03, &[]).unwrap();
        assert_eq!(run(&mut c, 0x1009, &[]).unwrap(), [0, 1, 2, 3, 4, 5, 6]);
    }

    #[test]
    fn vendor_reads_have_btbcm_lengths_and_optional_ones_fail_cleanly() {
        let mut c = Controller::default();
        // Public btbcm checks 7 and 9 bytes including the status.
        let verbose = run(&mut c, 0xfc79, &[]).unwrap();
        assert_eq!(verbose.len(), 7);
        assert_eq!(verbose[..2], [0, 122]);
        let features = run(&mut c, 0xfc6e, &[]).unwrap();
        assert_eq!(features.len(), 9);
        assert_eq!(features[..2], [0, 0x0f]);
        for (op, p) in [(0xfc16, &[0xc0, 0xff][..]), (0xfce9, &[4]), (0xfd53, &[])] {
            assert_eq!(run(&mut c, op, p).unwrap(), [UNKNOWN_COMMAND]);
        }
    }

    #[test]
    fn white_list_holds_its_announced_size() {
        let mut c = Controller::default();
        let size = run(&mut c, 0x200f, &[]).unwrap()[1];
        for i in 0..size {
            assert_eq!(run(&mut c, 0x2011, &[0, i, 0, 0, 0, 0, 0]).unwrap(), [0]);
        }
        // Adding a present entry again is no change; one more is too many.
        assert_eq!(run(&mut c, 0x2011, &[0, 0, 0, 0, 0, 0, 0]).unwrap(), [0]);
        let more = [0, size, 0, 0, 0, 0, 0];
        assert_eq!(
            run(&mut c, 0x2011, &more).unwrap(),
            [MEMORY_CAPACITY_EXCEEDED]
        );
        run(&mut c, 0x2012, &[0, 0, 0, 0, 0, 0, 0]).unwrap();
        assert_eq!(run(&mut c, 0x2011, &more).unwrap(), [0]);
    }

    #[test]
    fn le_rand_returns_fresh_numbers() {
        let mut c = Controller::default();
        let a = run(&mut c, 0x2018, &[]).unwrap();
        let b = run(&mut c, 0x2018, &[]).unwrap();
        assert_eq!((a.len(), a[0]), (9, 0));
        assert_ne!(a, b);
    }

    #[test]
    fn content_filter_counts_free_entries_per_type() {
        let mut c = Controller::default();
        // Sub-op 0, enable: status, sub-op, action (3 bytes).
        assert_eq!(run(&mut c, 0xfd57, &[0, 1]).unwrap(), [0, 0, 1]);
        // Sub-op 6, manufacturer data, add at index 1 (the firmware's own
        // command, shortened): status, sub-op, action, free entries.
        let add = [6, 0, 1, 0x53, 0x05, 1, 0xad, 0xde];
        let free = APCF_ENTRIES as u8;
        assert_eq!(run(&mut c, 0xfd57, &add).unwrap(), [0, 6, 0, free - 1]);
        // Another type is counted separately; clearing frees the type.
        assert_eq!(
            run(&mut c, 0xfd57, &[1, 0, 1, 0x20, 0, 0, 0, 1, 0x80, 0]).unwrap(),
            [0, 1, 0, free - 1]
        );
        assert_eq!(run(&mut c, 0xfd57, &[6, 2, 0]).unwrap(), [0, 6, 2, free]);
        for _ in 0..APCF_ENTRIES {
            run(&mut c, 0xfd57, &add).unwrap();
        }
        assert_eq!(
            run(&mut c, 0xfd57, &add).unwrap(),
            [MEMORY_CAPACITY_EXCEEDED, 6, 0, 0]
        );
        // Clearing every filter's parameters: sub-op and action only.
        assert_eq!(run(&mut c, 0xfd57, &[1, 2]).unwrap(), [0, 1, 2, free]);
        assert_eq!(
            run(&mut c, 0xfd57, &[1, 0, 1, 0x20, 0, 0, 0, 1, 0x80, 0]).unwrap(),
            [0, 1, 0, free - 1]
        );
        assert_eq!(run(&mut c, 0xfd57, &[8, 0, 0]), None);
    }

    #[test]
    fn unknown_or_malformed_commands_are_refused() {
        let mut c = Controller::default();
        assert_eq!(run(&mut c, 0x0401, &[0x33, 0x8b, 0x9e, 8, 0]), None);
        assert_eq!(run(&mut c, 0x0c03, &[0]), None);
        assert_eq!(run(&mut c, 0xfc18, &[1, 0, 0, 0, 0, 0]), None);
    }
}
