//! The Bluetooth half of the on-board BCM4356A3 combo chip, at the level of
//! its HCI command set: what `bluetooth` (Broadcom BSA/BTE stack) sends over
//! UART-D while it brings the controller up, and what it reads back.
//!
//! Command layouts and status codes are the Bluetooth Core Specification's
//! (Vol 4 Part E §7) as transcribed by public Linux
//! `include/net/bluetooth/hci.h`; supported-commands bit positions as listed
//! by public BlueZ `monitor/packet.c` (facts only). Broadcom vendor commands
//! follow public Linux `drivers/bluetooth/btbcm.c` and `hci_bcm.c`.
//!
//! Identity values (version, features, buffers) are what the real console's
//! controller reports where a public record of it exists (Switchbrew's
//! `hcitool info` of a Switch, see [`LMP_SUBVERSION`]); the remaining ones
//! are named assumptions, each with what the firmware does with it.
//!
//! The controller is present, powered and idle: it has no connections, so no
//! event other than Command Complete is ever generated by itself. Commands
//! this model does not know are refused, not acknowledged.
//!
//! Commands whose answer is a vendor feature or RF value that is not public
//! are split two ways. Where `bluetooth` treats the command as optional — it
//! ignores the answer or handles a failed status explicitly — the controller
//! answers status Unknown HCI Command: this model does not implement that
//! feature, and the firmware's own failure path is taken ([`OPTIONAL`] lists
//! each with the text offset that tolerates it). Anything else refuses.

/// HCI and LMP version 8 = Bluetooth 4.2. Switchbrew's `hcitool info` of a
/// Switch (Bluetooth_Driver_services, Notes) reads "LMP Version: 4.2 (0x8)";
/// the HCI version is assumed to be the same. `bluetooth` text 0xada80 only
/// tests it against 2 (to decide whether to read the supported commands).
const VERSION: u8 = 8;
/// HCI revision. Not publicly recorded for this patch; `bluetooth` text
/// 0xada80 stores it without testing it. Assumed 0.
const HCI_REVISION: u16 = 0;
/// Broadcom Corporation, company identifier 15 (Switchbrew `hcitool info`).
const MANUFACTURER: u16 = 15;
/// "LMP Subversion: 0x2409" (Switchbrew `hcitool info`); also public Linux
/// btbcm's BCM4356A3 entry (001.004.009).
const LMP_SUBVERSION: u16 = 0x2409;
/// LMP features page 0 and page 2 and the highest page, as Switchbrew's
/// `hcitool info` reports them. Page 1 holds the host's features, which
/// [`Controller::host_features`] tracks from the host's own writes (the
/// record shows 0x0f there: SSP, LE, simultaneous LE/BR-EDR and Secure
/// Connections enabled by the host).
const FEATURES: [u8; 8] = [0xbf, 0xfe, 0xcf, 0xfe, 0xdb, 0xff, 0x7b, 0x87];
const FEATURES_PAGE2: [u8; 8] = [0x7f, 0x0b, 0, 0, 0, 0, 0, 0];
const MAX_FEATURES_PAGE: u8 = 2;
/// ACL buffers: 1021 bytes x 8; SCO: 64 bytes x 1. Not recorded for this
/// console: assumed to be what Broadcom's UART controllers of the same
/// generation report in public `hciconfig` listings (e.g. the Raspberry Pi's
/// BCM43438, "ACL MTU: 1021:8 SCO MTU: 64:1"). `bluetooth` text 0xad440
/// sizes its ACL segmentation and credit count from them.
const ACL_LENGTH: u16 = 1021;
const ACL_PACKETS: u16 = 8;
const SCO_LENGTH: u8 = 64;
const SCO_PACKETS: u16 = 1;
/// LE buffers: length and count 0, the specification's way of saying LE data
/// shares the ACL buffers above (Vol 4 Part E §7.8.2). Not recorded for this
/// console; `bluetooth` text 0xad4c0 and 0xda440 handle exactly this case by
/// lending one ACL credit to LE.
const LE_BUFFERS: [u8; 3] = [0, 0, 0];
/// LE features: LE Encryption only, the Bluetooth 4.0 baseline. Not
/// recorded for this console; `bluetooth` text 0xad5d0 stores the mask and
/// gates optional LE procedures on it, so the baseline keeps it on the
/// commands every LE controller has.
const LE_FEATURES: [u8; 8] = [1, 0, 0, 0, 0, 0, 0, 0];
/// LE white list entries. Not recorded for this console; assumed 8.
/// `bluetooth` text 0xada30 stores it as the limit for white-list additions;
/// nothing is added while no device is paired.
const LE_WHITE_LIST_SIZE: u8 = 8;
/// LE supported states: the 29 state combinations Bluetooth 4.0 defines
/// (Vol 2 Part E §7.8.27 bits 0..28) — a 4.2 controller supports at least
/// the single states; assumed all 4.0 combinations. `bluetooth` text
/// 0xad520 stores the mask.
const LE_STATES: [u8; 8] = [0xff, 0xff, 0xff, 0x1f, 0, 0, 0, 0];
/// Entries the LE advertising packet content filter holds per filter type.
/// Not recorded for this console (its vendor-capabilities command 0xfd53 is
/// not answered, see [`OPTIONAL`]); assumed 16. `bluetooth` completion
/// 0x9b8a0 only counts with the free-entry number it gets back.
const APCF_ENTRIES: usize = 16;

/// HCI error codes (Vol 2 Part D).
const SUCCESS: u8 = 0;
const INVALID_PARAMETERS: u8 = 0x12;
const MEMORY_CAPACITY_EXCEEDED: u8 = 0x07;

/// A command this controller executes: opcode, parameter length
/// (`usize::MAX` = variable, checked in `execute`), and the (octet, bit) of
/// the Read Local Supported Commands mask that announces it (`None` for
/// commands the mask does not list).
type Command = (u16, usize, Option<(usize, u8)>);

