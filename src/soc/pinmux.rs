//! Pin multiplexer (`PINMUX_AUX`, `0x7000_3000`): one configuration
//! register per pin. `boot`'s pin driver reads all 175 into its tables,
//! clearing any park bit it finds (text `0x2e9e0`), and later programs
//! each pin's function, pull, tristate and input enable from its own
//! configuration. Like the other pure configuration blocks the registers
//! start at zero in a machine started at kernel entry.
//!
//! In a machine that runs the boot chain they start with the values the
//! NX bootloader's hardware-state check reads (`nxbl_hwcheck.csv`, the
//! check `0x40002A7C`, these rows at bootloader text
//! `0x40003490`..`0x40003DFE`), each row's expected value under its mask:
//! nearly every pin parked (bit 5), tristated (bit 4) with its input
//! enabled (bit 6) and a pull (bits 3:2). \[inference\] What a console's
//! pins hold when the bootloader starts, the check halting it on any
//! difference; they look like reset values, nothing public says the boot
//! ROM changes them. Two rows accept a second value, `0x40`, the value the
//! bootloader itself gives them (`0x700030DC`/`0x700030E0`, PWR_I2C, its
//! `0x40017550`); here they hold the first, `0x170`. Bits outside the
//! masks, and the six registers the check does not read (`0x018`, `0x034`,
//! `0x0A0`, `0x294`..`0x29C`), are \[assumption\] zero, as at kernel
//! entry.

use super::regs::RegisterFile;

pub const BASE: u64 = 0x7000_3000;
pub const SIZE: u64 = 0x300;

/// The block at kernel entry: every register zero.
pub fn at_kernel_entry() -> RegisterFile {
    RegisterFile::zeroed([])
}

/// The block as the SoC comes out of reset and the boot ROM leaves it.
pub fn power_on() -> RegisterFile {
    RegisterFile::zeroed(POWER_ON_STATE)
}

